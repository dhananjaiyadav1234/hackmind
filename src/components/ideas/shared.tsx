export function sortIdeasByRank(a: Idea, b: Idea): number {
  const ra = a.rank ?? Number.POSITIVE_INFINITY;
  const rb = b.rank ?? Number.POSITIVE_INFINITY;
  if (ra !== rb) return ra - rb;
  return (b.scores?.total ?? -1) - (a.scores?.total ?? -1);
}
