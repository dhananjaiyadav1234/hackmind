export function scoreColor(score10: number): string {
  if (score10 >= 7) return 'var(--color-good)';
  if (score10 >= 5) return 'var(--color-warn)';
  return 'var(--color-bad)';
}

/** Circular total score (0..100). */
export function ScoreRing({ value, size = 44 }: { value: number | null; size?: number }) {
  const r = (size - 6) / 2;
  const c = 2 * Math.PI * r;
  const v = value ?? 0;
  const color = scoreColor(v / 10);
  return (
    <div className="relative shrink-0" style={{ width: size, height: size }} role="img" aria-label={value === null ? 'Not scored' : `Total score ${value.toFixed(1)} out of 100`}>
      <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`} aria-hidden>
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke="var(--color-surface-3)" strokeWidth={4} />
        {value !== null && (
          <circle
            cx={size / 2}
            cy={size / 2}
            r={r}
            fill="none"
            stroke={color}
            strokeWidth={4}
            strokeLinecap="round"
            strokeDasharray={`${(Math.min(100, v) / 100) * c} ${c}`}
            transform={`rotate(-90 ${size / 2} ${size / 2})`}
          />
        )}
      </svg>
      <span className="absolute inset-0 grid place-items-center font-mono text-[11px] font-semibold tabular-nums text-fg">{value === null ? '—' : Math.round(v)}</span>
    </div>
  );
}

export function safeHref(url: string | undefined | null): string | null {
  if (!url) return null;
  try {
    const u = new URL(url);
    return u.protocol === 'http:' || u.protocol === 'https:' ? u.toString() : null;
  } catch {
    return null;
  }
}

export function ExtLink({ href, children, className }: { href?: string | null; children: ReactNode; className?: string }) {
  const safe = safeHref(href);
  if (!safe) return <span className={className}>{children}</span>;
  return (
    <a href={safe} target="_blank" rel="noreferrer noopener" className={cn('inline-flex items-center gap-1 text-info underline-offset-2 hover:underline', className)}>
      {children}
      <ExternalLink className="h-3 w-3 shrink-0" aria-hidden />
    </a>
  );
}

/** Clickable chip that opens the evidence drawer for a source id. */
export function SourceChip({ id, sources, onOpen }: { id: string; sources: Map<string, Source>; onOpen?: (id: string) => void }) {
  const s = sources.get(id);
  const label = s ? s.title || s.url : id;
  return (
    <button
      type="button"
      onClick={() => onOpen?.(id)}
      disabled={!onOpen}
      title={s ? `${s.title} — ${s.url}` : `Source ${id} (not loaded)`}
      className="inline-flex max-w-[16rem] items-center gap-1 rounded-full border border-line-strong bg-surface-2 px-2 py-0.5 text-[11px] text-muted hover:border-accent hover:text-fg disabled:cursor-default"
    >
      <FileText className="h-3 w-3 shrink-0" aria-hidden />
      <span className="truncate">{label}</span>
    </button>
  );
}

export function SourceChips({ ids, sources, onOpen }: { ids: string[]; sources: Map<string, Source>; onOpen?: (id: string) => void }) {
  if (!ids.length) return null;
  return (
    <span className="inline-flex flex-wrap gap-1">
      {ids.map((id) => (
        <SourceChip key={id} id={id} sources={sources} onOpen={onOpen} />
      ))}
    </span>
  );
}

export function topSponsors(idea: Idea, n = 2): string[] {
  const seen: string[] = [];
  for (const s of idea.sponsorIntegration) if (!seen.includes(s.sponsor)) seen.push(s.sponsor);
  return seen.slice(0, n);
}

export function criterionScore(idea: Idea, c: Criterion): number | null {
  return idea.scores?.criteria[c]?.score ?? null;
}

