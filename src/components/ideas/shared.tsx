/** Heat-map background for a 0..10 score. */
export function heatStyle(score: number | null): CSSProperties {
  if (score === null) return {};
  const color = scoreColor(score);
  const alpha = Math.round(12 + (score / 10) * 28);
  return { backgroundColor: `color-mix(in srgb, ${color} ${alpha}%, transparent)` };
}

